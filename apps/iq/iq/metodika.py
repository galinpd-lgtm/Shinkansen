"""Публичното описание на методиката — от текущата конфигурация, за да не се разминава с кода."""
from .dov import IMENA_OSI, OSI_KLUCHOVE
from .tekstove import chislo, procent


def _usloviya(s):
    u = []
    if "min_imenuvani" in s:
        u.append("поне %s от записите с именувани източници" % procent(s["min_imenuvani"]))
    if "maks_pohvati" in s:
        u.append("под %s от записите с манипулативни похвати" % procent(s["maks_pohvati"]))
    if "min_istoriya_dni" in s:
        u.append("поне %d дни история" % s["min_istoriya_dni"])
    if "min_uverenost" in s:
        u.append("поне %s от записите със средна или висока увереност на оценката (оценка с модел)"
                 % procent(s["min_uverenost"]))
    if "min_sedmici_s_publikacii" in s:
        u.append("публикации в поне %d от седмиците на периода" % s["min_sedmici_s_publikacii"])
    return "; ".join(u) or "—"


def tablica(cfg):
    redove = ["| Степен | Средна оценка | Условия | Цвят |", "|---|---|---|---|"]
    gore = 10.0
    for s in cfg["stepeni"]:
        redove.append("| %s | %s–%s | %s | %s |" % (s["kod"], chislo(s["ot"]), chislo(gore), _usloviya(s),
                                                    s["cvyat_ime"]))
        gore = round(s["ot"] - 0.1, 1)
    b, sp = cfg["bez_stepen"], cfg["spryana"]
    redove.append("| %s | под %s, или под %d оценени записа, или под %d дни история | недостатъчно данни | %s |" % (
        b["kod"], chislo(cfg["stepeni"][-1]["ot"]), b["min_zapisi"], b["min_istoriya_dni"], b["cvyat_ime"]))
    redove.append("| %s | — | само ръчно решение на човек с писмено основание | %s |" % (sp["kod"], sp["cvyat_ime"]))
    return "\n".join(redove)


def tekst(cfg):
    osi = "\n".join("   %d. %s" % (i, IMENA_OSI[k]) for i, k in enumerate(OSI_KLUCHOVE, 1))
    return """# Методика: степен на качество на информационен канал

Версия на методиката: 0.1. Този текст се генерира от същата конфигурация, по която се смята степента.

## Какво се оценява

Оценява се **информационен канал** — медия, сайт или бюлетин. **Не се оценяват хора**: нито журналисти, нито
автори, нито редактори. Авторът на отделен текст не влиза в сметката.

## Откъде идват данните

1. Информационният филтър събира публично достъпни текстове на канала (емисии и страници, които не са отказали
   машинно извличане).
2. Всеки текст получава **профил на доверие** по 7 оси (0–10):
%s
   и се проверява за 14 манипулативни похвата. Профилът описва текста — не казва дали твърденията в него са
   верни.
3. Степента се смята от профилите на текстовете за последните **%d дни**. Преизчислява се веднъж седмично.

## Числата

- **Средна оценка** — средното от крайните оценки на текстовете за периода, закръглено до 1 знак. Същото
  закръглено число решава степента.
- **Записи с именувани източници** — дял на текстовете, чиято ос „Прозрачност на източниците“ е поне %s
  (т.е. именуваните източници в текста са поне колкото анонимните).
- **Записи с манипулативни похвати** — дял на текстовете с поне един открит похват.
- **Записи с достатъчна увереност** — дял на текстовете, чиято оценка е със средна или висока увереност.
  Оценката само по правила (без езиков модел) е с ниска увереност; затова без достатъчно оценки с модел
  най-високата възможна степен е по-ниска от A.
- **История** — дни от първия оценен текст на канала до края на периода.
- **Седмици с публикации** — в колко от седмиците на периода има поне един оценен текст.

## Степените

%s

Ако каналът е в обхвата на дадена степен, но не изпълнява условията ѝ, се проверява следващата степен надолу.
Когато степента се влоши спрямо предишното изчисление, това се записва във вътрешен дневник на промените.

„%s“ **никога не се поставя от машината**. Поставя се само от човек, с писмено основание, роля и дата.

## Какво не може да се заключи

- Степента описва текстовете, които филтърът е събрал за периода, а не всичко, публикувано от канала.
- Тя не е проверка на факти и не казва дали отделно твърдение е вярно или невярно.
- Тя не е оценка на хората, които работят в канала.
- Оценките без езиков модел са груби (само правила); увереността в тях е ниска и това се посочва в отчета.
- Степента не е сертификат от независим орган.

## Публикуване

Отчет и значка за конкретен канал се издават само по поръчка и със съгласие на самия канал. Без съгласие
те могат да се създадат само за вътрешна употреба и носят надпис „вътрешно · непубликувано“.
""" % (osi, cfg["prozorec_dni"], chislo(cfg["imenuvani_prag"]), tablica(cfg), cfg["spryana"]["kod"])
